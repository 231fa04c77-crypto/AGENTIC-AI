def expand(base: list[str], extras: list[str], n: int = 20) -> list[str]:
    out = list(dict.fromkeys(base + extras))
    i = 0
    while len(out) < n:
        out.append(f"{base[i % len(base)]} please")
        i += 1
        if i > 50:
            break
    return out[: max(n, len(base))]


